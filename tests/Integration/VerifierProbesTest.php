<?php

declare(strict_types=1);

namespace CleanPlugins\Scoper\Tests\Integration;

use CleanPlugins\Scoper\Exception\ScoperException;
use CleanPlugins\Scoper\Support\Filesystem;
use CleanPlugins\Scoper\Tests\TestCase;
use CleanPlugins\Scoper\Verify\Verifier;

final class VerifierProbesTest extends TestCase
{
    public function testRunsTheProbeForAnInstalledPackageAndSkipsAnAbsentOne(): void
    {
        $config = $this->config([
            'verify' => [
                'acme/library' => 'tools/verify-library.php',
                'acme/other' => 'tools/verify-other.php',
            ],
        ]);
        $this->buildTree();

        $result = (new Verifier($config, new Filesystem($this->tmp)))->run();

        self::assertContains('Probe acme/library: library ok', $result->lines);
        self::assertNotContains('Probe acme/other: other ok', $result->lines);
        self::assertGreaterThan(0, $result->checks);
    }

    public function testFailsWhenAProbeFileIsMissing(): void
    {
        $config = $this->config([
            'verify' => [
                'acme/library' => 'tools/missing.php',
            ],
        ]);
        $this->buildTree();

        try {
            (new Verifier($config, new Filesystem($this->tmp)))->run();
        } catch (ScoperException $exception) {
            self::assertStringContainsString('checks failed', $exception->getMessage());
            self::assertStringContainsString('Probe file not found for acme/library', implode("\n", $exception->details));

            return;
        }

        self::fail('Expected the verifier to fail');
    }

    public function testFailsWhenAProbeReadsTheRemovedConfigVariable(): void
    {
        $config = $this->config([
            'verify' => [
                'acme/library' => 'tools/verify-config.php',
            ],
        ]);
        $this->buildTree();
        $this->write('tools/verify-config.php', "<?php\n\nreturn \$config['prefix'];\n");

        try {
            (new Verifier($config, new Filesystem($this->tmp)))->run();
        } catch (ScoperException $exception) {
            self::assertStringContainsString('Undefined variable $config', implode("\n", $exception->details));

            return;
        }

        self::fail('Expected the verifier to fail');
    }

    public function testVendorWarningsInsideAProbeDoNotFailIt(): void
    {
        $config = $this->config([
            'verify' => [
                'acme/library' => 'tools/verify-warns.php',
            ],
        ]);
        $this->buildTree();
        $this->write('build/vendor/acme/library/src/warns.php', "<?php\n\ntrigger_error('vendor noise', E_USER_WARNING);\n");
        $this->write('tools/verify-warns.php', "<?php\n\nrequire __DIR__ . '/../build/vendor/acme/library/src/warns.php';\n\nreturn 'library ok';\n");

        $result = (new Verifier($config, new Filesystem($this->tmp)))->run();

        self::assertContains('Probe acme/library: library ok', $result->lines);
    }

    public function testFailsWhenAProbeFileDoesNotReturnAString(): void
    {
        $config = $this->config([
            'verify' => [
                'acme/library' => 'tools/verify-bad.php',
            ],
        ]);
        $this->buildTree();
        $this->write('tools/verify-bad.php', "<?php\n\nreturn ['not', 'a string'];\n");

        try {
            (new Verifier($config, new Filesystem($this->tmp)))->run();
        } catch (ScoperException $exception) {
            self::assertStringContainsString('Probe for acme/library must return a string', implode("\n", $exception->details));

            return;
        }

        self::fail('Expected the verifier to fail');
    }

    private function buildTree(): void
    {
        $this->write('build/vendor/autoload.php', <<<'PHP'
        <?php

        // @generated by the build

        spl_autoload_register(static function (string $class): void {
            $map = [
                'Acme\\Library\\Thing' => __DIR__ . '/acme/library/src/Thing.php',
                'Acme\\Project\\Plugin' => __DIR__ . '/../src/Plugin.php',
            ];

            if (isset($map[$class])) {
                require $map[$class];
            }
        });
        PHP);

        $this->write('build/vendor/acme/library/src/Thing.php', <<<'PHP'
        <?php

        namespace Acme\Library;

        class Thing
        {
        }
        PHP);

        $this->write('build/src/Plugin.php', <<<'PHP'
        <?php

        namespace Acme\Project;

        class Plugin
        {
        }
        PHP);

        $this->write('.build/installed.json', json_encode([
            'packages' => [
                ['name' => 'acme/library'],
            ],
        ], JSON_PRETTY_PRINT) . PHP_EOL);
        $this->write('.build/prefix-map.json', "{}\n");

        $this->write('tools/verify-library.php', "<?php\n\ndeclare(strict_types=1);\n\nreturn isset(\$config) ? 'config leaked' : 'library ok';\n");
        $this->write('tools/verify-other.php', "<?php\n\ndeclare(strict_types=1);\n\nreturn 'other ok';\n");
    }
}
