<?php

/**
 * Verifies a staged tree in a clean PHP process that has only the generated autoloader.
 *
 * The build process has the project's dev autoloader loaded; requiring the staged loader there
 * could redeclare the project's own autoload `files` or make an unscoped class reachable. This
 * script is the isolation boundary. It prints one JSON object; the parent turns failures into an
 * exception.
 */

declare(strict_types=1);

$settings = json_decode((string) file_get_contents($argv[1]), true);

if (!is_array($settings)) {
    fwrite(STDERR, "verify runner: invalid config\n");
    exit(1);
}

$autoloaderPath = $argv[2];
$mapPath = $argv[3];
$installedPath = $argv[4];
$buildDir = rtrim(str_replace('\\', '/', $argv[5]), '/');
$vendor = trim($argv[6], '/');
$classRoots = $settings['classRoots'] ?? [];
$ignoredPaths = $settings['ignoredPaths'] ?? [];
$probeFiles = is_array($settings['probes'] ?? null) ? $settings['probes'] : [];
$map = is_file($mapPath) ? (json_decode((string) file_get_contents($mapPath), true) ?: []) : [];
$installed = is_file($installedPath) ? (json_decode((string) file_get_contents($installedPath), true) ?: []) : [];
$failures = [];
$lines = [];
$checks = 0;

$fail = static function (string $message) use (&$failures, &$checks): void {
    ++$checks;
    $failures[] = $message;
};

$pass = static function () use (&$checks): void {
    ++$checks;
};

// 1. Composer's autoloader must not be shipped, and ours must be the one that is.
if (is_dir($buildDir . '/' . $vendor . '/composer')) {
    $fail("{$vendor}/composer/ is still present; Composer's autoloader must not be shipped");
} else {
    $pass();
}

$autoloader = is_file($autoloaderPath) ? (string) file_get_contents($autoloaderPath) : '';

if (!str_contains($autoloader, '@generated by the build')) {
    $fail("{$autoloaderPath} is missing or was not generated by the build");
} else {
    $pass();
}

$loaded = true;

if (is_file($autoloaderPath)) {
    $loaded = false;
    register_shutdown_function(static function () use (&$loaded): void {
        if (!$loaded) {
            fwrite(STDERR, "verify runner: aborted — code required by the autoloader called exit()\n");
            exit(1);
        }
    });

    require $autoloaderPath;
    $loaded = true;
}

// 2. Every class declared in the scoped tree must autoload through the generated classmap.
$declared = [];
$roots = array_values(array_unique(array_merge([$vendor], $classRoots)));

foreach ($roots as $root) {
    if (!is_dir($buildDir . '/' . $root) && !is_file($buildDir . '/' . $root)) {
        $fail("missing {$root}");

        continue;
    }

    foreach (scoper_php_files($buildDir . '/' . $root) as $full) {
        $relative = scoper_relative($buildDir, $full);

        if (scoper_is_ignored($relative, $ignoredPaths)) {
            continue;
        }

        $contents = (string) file_get_contents($full);

        if (preg_match('/^namespace\s+([^;]+);/m', $contents, $namespace) !== 1) {
            $namespace = ['', ''];
        }

        if (preg_match_all('/^(?:\s*)(?:final\s+|abstract\s+|readonly\s+)*(class|interface|trait|enum)\s+(\w+)/m', $contents, $symbols, PREG_SET_ORDER) === 0) {
            continue;
        }

        foreach ($symbols as $symbol) {
            $declared[trim($namespace[1]) === '' ? $symbol[2] : trim($namespace[1]) . '\\' . $symbol[2]] = $relative;
        }
    }
}

if ($declared === []) {
    $fail('No classes were found in the scoped tree — is the build complete?');
} else {
    $pass();
}

$unloadable = [];

foreach (array_keys($declared) as $class) {
    try {
        if (!class_exists($class) && !interface_exists($class) && !trait_exists($class) && !enum_exists($class)) {
            $unloadable[] = $class;
        }
    } catch (Throwable $exception) {
        $unloadable[] = sprintf('%s (%s)', $class, $exception->getMessage());
    }
}

if ($unloadable === []) {
    $pass();
} else {
    $fail(sprintf('Declared but not loadable through the classmap: %s', implode(', ', array_slice($unloadable, 0, 5))));
}

$lines[] = sprintf('Checked %d declared classes in the scoped tree', count($declared));

// 3. References rewritten inside an ignored package must resolve to something we ship.
if ($map !== []) {
    $unresolved = [];
    $checked = 0;

    foreach ($map['edits'] ?? [] as $file => $edits) {
        if (!scoper_is_ignored((string) $file, $ignoredPaths)) {
            continue;
        }

        foreach ($edits as $edit) {
            ++$checked;
            $target = $edit['to'];

            if (!class_exists($target) && !interface_exists($target) && !trait_exists($target) && !enum_exists($target) && !scoper_is_namespace($target, $map['namespaces'] ?? [])) {
                $unresolved[] = $target;
            }
        }
    }

    if ($unresolved === []) {
        $pass();
        $lines[] = sprintf('Checked %d rewritten reference(s) inside ignored packages', $checked);
    } else {
        $fail(sprintf('Rewritten references inside ignored packages do not resolve: %s', implode(', ', array_slice(array_unique($unresolved), 0, 5))));
    }
}

// 4. Behaviour probes, for installed packages only. Each file is static: it receives no config and
// returns a description string. A warning raised by the probe file itself (notably reading the
// removed `$config`) fails the probe; warnings from code it happens to load do not.
foreach ($probeFiles as $package => $probePath) {
    $package = (string) $package;
    $probePath = (string) $probePath;

    if (!is_file($probePath)) {
        $fail("Probe file not found for {$package}: {$probePath}");

        continue;
    }

    $directory = scoper_package_directory($package, $installed, $vendor);

    if (!is_dir($buildDir . '/' . $directory)) {
        continue;
    }

    try {
        $probe = str_replace('\\', '/', (string) (realpath($probePath) ?: $probePath));

        set_error_handler(static function (int $severity, string $message, string $file, int $line) use ($probe): bool {
            $reported = str_replace('\\', '/', (string) (realpath($file) ?: $file));
            $same = PHP_OS_FAMILY === 'Windows' ? strcasecmp($reported, $probe) === 0 : $reported === $probe;

            if (!$same) {
                return false;
            }

            throw new ErrorException($message, 0, $severity, $file, $line);
        }, E_WARNING | E_NOTICE | E_USER_WARNING | E_USER_NOTICE);

        try {
            $result = (static function (string $probePath): mixed {
                return require $probePath;
            })($probePath);
        } finally {
            restore_error_handler();
        }

        if (!is_string($result)) {
            $fail("Probe for {$package} must return a string");

            continue;
        }

        $pass();
        $lines[] = sprintf('Probe %s: %s', $package, $result);
    } catch (Throwable $exception) {
        $fail(sprintf('Probe %s failed: %s', $package, $exception->getMessage()));
    }
}

// 5. The project's own code must not still import an unscoped dependency namespace.
$ownImports = [];

foreach (scoper_php_files($buildDir) as $full) {
    $relative = scoper_relative($buildDir, $full);

    if (str_starts_with($relative, $vendor . '/')) {
        continue;
    }

    $contents = (string) file_get_contents($full);

    foreach (array_keys($map['namespaces'] ?? []) as $namespace) {
        if (preg_match('/^use\s+' . preg_quote((string) $namespace, '/') . '\\\\/m', $contents) === 1) {
            $ownImports[] = "{$relative} still imports {$namespace}";
        }
    }
}

if ($ownImports === []) {
    $pass();
} else {
    $fail('Own code still imports unscoped namespaces');
    $lines = array_merge($lines, $ownImports);
}

fwrite(STDOUT, json_encode(['checks' => $checks, 'failures' => $failures, 'lines' => $lines], JSON_UNESCAPED_SLASHES) ?: '{}');

/** @return list<string> */
function scoper_php_files(string $path): array
{
    if (is_file($path)) {
        return str_ends_with($path, '.php') ? [str_replace('\\', '/', $path)] : [];
    }

    if (!is_dir($path)) {
        return [];
    }

    $files = [];
    $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS));

    /** @var SplFileInfo $file */
    foreach ($iterator as $file) {
        if ($file->isFile() && $file->getExtension() === 'php') {
            $files[] = str_replace('\\', '/', $file->getPathname());
        }
    }

    sort($files);

    return $files;
}

function scoper_relative(string $base, string $path): string
{
    $base = rtrim(str_replace('\\', '/', $base), '/');
    $path = str_replace('\\', '/', $path);

    return $path === $base ? '' : ltrim(substr($path, strlen($base)), '/');
}

/** @param list<string> $patterns */
function scoper_is_ignored(string $relative, array $patterns): bool
{
    $relative = trim($relative, '/');

    foreach ($patterns as $pattern) {
        $pattern = trim((string) $pattern, '/');

        if ($pattern === '') {
            continue;
        }

        if (!str_contains($pattern, '*')) {
            $prefix = $pattern . '/';

            if (strcasecmp($relative, $pattern) === 0 || strncasecmp($relative, $prefix, strlen($prefix)) === 0) {
                return true;
            }

            continue;
        }

        $regex = scoper_glob_regex($pattern);
        $candidate = $relative;

        while (true) {
            if (preg_match($regex, $candidate) === 1) {
                return true;
            }

            $parent = dirname($candidate);

            if ($parent === '.' || $parent === '' || $parent === $candidate) {
                break;
            }

            $candidate = str_replace('\\', '/', $parent);
        }
    }

    return false;
}

function scoper_glob_regex(string $pattern): string
{
    $regex = '';
    $length = strlen($pattern);

    for ($i = 0; $i < $length; ++$i) {
        $char = $pattern[$i];

        if ($char === '*') {
            if (($pattern[$i + 1] ?? '') === '*') {
                if (($pattern[$i + 2] ?? '') === '/') {
                    $regex .= '(?:[^/]+/)*';
                    $i += 2;

                    continue;
                }

                $regex .= '.*';
                ++$i;

                continue;
            }

            $regex .= '[^/]*';

            continue;
        }

        $regex .= preg_quote($char, '#');
    }

    return '#^' . $regex . '$#i';
}

function scoper_is_namespace(string $value, array $namespaces): bool
{
    foreach (array_keys($namespaces) as $namespace) {
        if ($value === $namespace || str_starts_with($value, $namespace . '\\')) {
            return true;
        }
    }

    return false;
}

function scoper_package_directory(string $package, array $installed, string $vendor): string
{
    foreach ((array) ($installed['packages'] ?? []) as $entry) {
        if (($entry['name'] ?? null) !== $package) {
            continue;
        }

        $install = $entry['install-path'] ?? null;

        if (!is_string($install) || $install === '') {
            return $vendor . '/' . $package;
        }

        return scoper_normalize($vendor . '/composer/' . $install);
    }

    return $vendor . '/' . $package;
}

function scoper_normalize(string $path): string
{
    $parts = [];

    foreach (explode('/', str_replace('\\', '/', $path)) as $part) {
        if ($part === '' || $part === '.') {
            continue;
        }

        if ($part === '..') {
            array_pop($parts);

            continue;
        }

        $parts[] = $part;
    }

    return implode('/', $parts);
}
